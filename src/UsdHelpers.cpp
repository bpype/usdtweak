inline void increment(std::string &number) {
    unsigned char ret = 1;
    // if (number == "") number = "0000"; // 4 padding default ? is it useful ?
    for (int i = number.size() - 1; i >= 0; i--) {
        if (ret) {
            number[i] += ret;
        }
        if (number[i] > '9') {
            number[i] = '0';
            ret = 1;
        } else {
            ret = 0;
        }
    }
    if (ret == 1) {
        number = "1" + number;
    }
}

std::string FindNextAvailableTokenString(std::string prefix) {
    // Find number in the prefix
    size_t end = prefix.size() - 1;
    while (end > 0 && std::isdigit(prefix[end])) {
        end--;
    }
    size_t padding = prefix.size() - 1 - end;
    std::string number = prefix.substr(end + 1, padding);
    std::string newName;
    do {
        increment(number);
        newName = prefix.substr(0, end + 1) + number;
    } while (TfToken::Find(newName) != TfToken());
    return newName;
}

const std::vector<std::string> GetUsdValidExtensions() {
    const auto usdExtensions = SdfFileFormat::FindAllFileFormatExtensions();
    std::vector<std::string> validExtensions;
    auto addDot = [](const std::string &str) { return "." + str; };
    std::transform(usdExtensions.cbegin(), usdExtensions.cend(), std::back_inserter(validExtensions), addDot);
    return validExtensions;
}

EditBlocked GetEditBlocked(const UsdPrim &prim) {
    if (prim.IsInstanceProxy())
        return EditBlocked::InstanceProxy;
    if (prim.IsPrototype() || prim.IsInPrototype())
        return EditBlocked::Prototype;
    const UsdEditTarget editTarget = prim.GetStage()->GetEditTarget();
    const SdfLayerHandle layer = editTarget.GetLayer();
    if (!layer)
        return EditBlocked::NoEditTarget;
    if (editTarget.MapToSpecPath(prim.GetPath()).IsEmpty())
        return EditBlocked::PrimNotMapped;
    if (!layer->PermissionToEdit())
        return EditBlocked::LayerReadOnly;
    if (layer->GetFileFormat() && !layer->GetFileFormat()->SupportsEditing())
        return EditBlocked::FormatNotEditable;
    return EditBlocked::None;
}

/// The instance providing the instance proxy prim
static UsdPrim GetInstanceOfProxy(const UsdPrim &prim) {
    UsdPrim instance = prim.GetParent();
    while (instance && !instance.IsInstance()) {
        instance = instance.GetParent();
    }
    return instance;
}

std::string GetEditBlockedReason(const UsdPrim &prim) {
    const SdfLayerHandle layer = prim.GetStage()->GetEditTarget().GetLayer();
    const std::string layerName = layer ? layer->GetDisplayName() : std::string();
    switch (GetEditBlocked(prim)) {
    case EditBlocked::None:
        return {};
    case EditBlocked::InstanceProxy:
        return "This prim is an instance proxy, USD doesn't allow editing it.\n"
               "Edit the asset it comes from in the layer editor, or turn off Instanceable on " +
               GetInstanceOfProxy(prim).GetPath().GetString() + ".";
    case EditBlocked::Prototype:
        return "This prim belongs to a prototype generated by USD, it can't be edited.\n"
               "Edit the asset its instances come from in the layer editor, or turn off Instanceable on the instances.";
    case EditBlocked::NoEditTarget:
        return "The stage has no edit target.\nChoose one with the edit target button.";
    case EditBlocked::PrimNotMapped:
        return "The edit target " + layerName + " doesn't contain this prim.\nChoose another one with the edit target button.";
    case EditBlocked::LayerReadOnly:
        return "The edit target " + layerName + " is read-only.\nChoose another one with the edit target button.";
    case EditBlocked::FormatNotEditable:
        return "The file format of the edit target " + layerName +
               " doesn't support editing.\nChoose another one with the edit target button.";
    }
    return {};
}

static int FindNodeIndex(const PcpPrimIndex &primIndex, const PcpNodeRef &node) {
    const PcpNodeRange range = primIndex.GetNodeRange();
    int index = 0;
    for (auto it = range.first; it != range.second; ++it, ++index) {
        if (*it == node)
            return index;
    }
    return -1;
}

static int FindLayerIndex(const PcpNodeRef &node, const SdfLayerHandle &layer) {
    const SdfLayerRefPtrVector &layers = node.GetLayerStack()->GetLayers();
    for (int index = 0; index < static_cast<int>(layers.size()); ++index) {
        if (layers[index] == layer)
            return index;
    }
    return -1;
}

OpinionStrength GetEditTargetStrength(const UsdPrim &prim) {
    const UsdEditTarget editTarget = prim.GetStage()->GetEditTarget();
    const SdfPath specPath = editTarget.MapToSpecPath(prim.GetPath());
    const PcpPrimIndex &primIndex = prim.GetPrimIndex();
    const PcpNodeRange range = primIndex.GetNodeRange();
    int nodeIndex = 0;
    for (auto it = range.first; it != range.second; ++it, ++nodeIndex) {
        if (it->GetPath() == specPath) {
            const int layerIndex = FindLayerIndex(*it, editTarget.GetLayer());
            if (layerIndex >= 0)
                return {nodeIndex, layerIndex};
        }
    }
    return {};
}

/// The strongest layer of the node holding a value opinion (default, block, time samples or spline) for the attribute
static int FindStrongestValueLayer(const PcpNodeRef &node, const TfToken &attributeName) {
    const SdfPath specPath = node.GetPath().AppendProperty(attributeName);
    const SdfLayerRefPtrVector &layers = node.GetLayerStack()->GetLayers();
    for (int index = 0; index < static_cast<int>(layers.size()); ++index) {
        if (layers[index]->HasField(specPath, SdfFieldKeys->Default) ||
            layers[index]->HasField(specPath, SdfFieldKeys->TimeSamples) ||
            layers[index]->HasField(specPath, SdfFieldKeys->Spline)) {
            return index;
        }
    }
    return -1;
}

static bool IsStrongerThan(const OpinionStrength &opinion, const OpinionStrength &other) {
    return opinion.node < other.node || (opinion.node == other.node && opinion.layer < other.layer);
}

std::optional<ShadowingOpinion> FindShadowingOpinion(const UsdAttribute &attribute, UsdTimeCode time,
                                                     const OpinionStrength &editTargetStrength) {
    if (!attribute || !editTargetStrength.HasNode())
        return std::nullopt;
    const UsdResolveInfo resolveInfo = attribute.GetResolveInfo(time);
    const PcpNodeRef node = resolveInfo.GetNode();
    if (!resolveInfo.HasAuthoredValueOpinion() || !node)
        return std::nullopt;
    const bool fromClips = resolveInfo.GetSource() == UsdResolveInfoSourceValueClips;
    const OpinionStrength valueStrength{FindNodeIndex(attribute.GetPrim().GetPrimIndex(), node),
                                        fromClips ? -1 : FindStrongestValueLayer(node, attribute.GetName())};
    // The layer of value clips is unknown, we only compare when they come from another node
    if (!valueStrength.HasNode() || (valueStrength.layer < 0 && valueStrength.node == editTargetStrength.node))
        return std::nullopt;
    if (!IsStrongerThan(valueStrength, editTargetStrength))
        return std::nullopt;

    ShadowingOpinion opinion;
    opinion.path = node.GetPath().AppendProperty(attribute.GetName());
    if (fromClips) {
        opinion.source = "value clips introduced in " + node.GetLayerStack()->GetIdentifier().rootLayer->GetDisplayName();
    } else {
        opinion.source = node.GetLayerStack()->GetLayers()[valueStrength.layer]->GetDisplayName();
    }
    return opinion;
}

std::string FormatShadowingOpinion(const ShadowingOpinion &opinion, const UsdStageWeakPtr &stage) {
    const SdfLayerHandle editLayer = stage->GetEditTarget().GetLayer();
    const std::string editTargetName = editLayer ? editLayer->GetDisplayName() : std::string();
    return "This value comes from a stronger opinion: " + opinion.source + " " + opinion.path.GetString() + "\n" +
           "Edits in the edit target " + editTargetName + " are hidden by it.";
}
